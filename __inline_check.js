let audioCtx=null;
let audioUnlocked=false;
function initAudio(){
  if(!audioEnabled) return;
  if(audioUnlocked) return;
  try{
    audioCtx = audioCtx || new (window.AudioContext || window.webkitAudioContext)();
    if(audioCtx.state==="suspended") audioCtx.resume();
    audioUnlocked=true;
  }catch(e){ audioUnlocked=false; }
}
function playPointSound(amount=10){
  if(!audioEnabled || !audioUnlocked || !audioCtx) return;
  const now=audioCtx.currentTime;
  const base=520;
  const boost=Math.min(420, Math.max(0, amount*6));
  const o1=audioCtx.createOscillator(), g1=audioCtx.createGain();
  o1.type="triangle";
  o1.frequency.setValueAtTime(base, now);
  o1.frequency.exponentialRampToValueAtTime(base+boost, now+0.08);
  g1.gain.setValueAtTime(0.0001, now);
  g1.gain.exponentialRampToValueAtTime(0.22, now+0.02);
  g1.gain.exponentialRampToValueAtTime(0.0001, now+0.14);
  o1.connect(g1).connect(audioCtx.destination);
  o1.start(now); o1.stop(now+0.16);

  const o2=audioCtx.createOscillator(), g2=audioCtx.createGain();
  o2.type="sine";
  o2.frequency.setValueAtTime(base+120, now+0.06);
  o2.frequency.exponentialRampToValueAtTime(base+boost+260, now+0.14);
  g2.gain.setValueAtTime(0.0001, now+0.06);
  g2.gain.exponentialRampToValueAtTime(0.18, now+0.085);
  g2.gain.exponentialRampToValueAtTime(0.0001, now+0.22);
  o2.connect(g2).connect(audioCtx.destination);
  o2.start(now+0.06); o2.stop(now+0.24);
}

