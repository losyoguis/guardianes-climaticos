function sanitizeFilenamePart(value){
  const raw = String(value || '').trim();
  if(!raw) return currentLang==='en' ? 'student' : 'estudiante';
  return raw.normalize('NFD').replace(/[\u0300-\u036f]/g,'').replace(/[^a-zA-Z0-9]+/g,'_').replace(/^_+|_+$/g,'').toLowerCase() || (currentLang==='en' ? 'student' : 'estudiante');
}
