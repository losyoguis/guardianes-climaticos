let narrationActive = false;

function stopNarration(){
  try{
    if("speechSynthesis" in window){
      window.speechSynthesis.cancel();
    }
  }catch(e){}
  narrationActive = false;
}

function pickVoiceFor(langPrefix){
  try{
    const voices = window.speechSynthesis.getVoices ? window.speechSynthesis.getVoices() : [];
    if(!voices || !voices.length) return null;
    const pref = voices.find(v => (v.lang || "").toLowerCase().startsWith(langPrefix.toLowerCase()));
    return pref || null;
  }catch(e){
    return null;
  }
}

function speakText(text){
  if(!text) return;
  if(!audioEnabled){
    showToast((currentLang==="en") ? "Audio is muted 🔇" : "El audio está silenciado 🔇");
    return;
  }
  if(!("speechSynthesis" in window) || typeof SpeechSynthesisUtterance === "undefined"){
    showToast(t("t_tts_not_supported"));
    return;
  }

  stopNarration();

  const langCode = (currentLang === "en") ? "en-US" : "es-CO";
  const u = new SpeechSynthesisUtterance(text);
  u.lang = langCode;

  const v = pickVoiceFor(currentLang === "en" ? "en" : "es");
  if(v) u.voice = v;

  u.rate = 0.98;
  u.pitch = 1.04;
  u.volume = 1;

  u.onend = ()=>{ narrationActive=false; };
  u.onerror = ()=>{ narrationActive=false; };

  narrationActive = true;
  window.speechSynthesis.speak(u);
}

