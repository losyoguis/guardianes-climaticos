function getNearestBusLevel(clientX){
  const lanes=getDragLanes("bus");
  if(!lanes.length) return null;
  let best=null;
  let bestDist=Infinity;
  lanes.forEach(l=>{
    const r=l.getBoundingClientRect();
    const center=r.left+(r.width/2);
    const dist=Math.abs(clientX-center);
    if(dist<bestDist){
      bestDist=dist;
      best=l.getAttribute("data-level");
    }
  });
  return best;
}

function shiftBusLevel(direction=1, announce=true){
  const levels=["low","mid","high"];
  const currentIdx=levels.indexOf(vehPick.bus || "");
  let idx=currentIdx;
  if(idx<0) idx = direction > 0 ? -1 : levels.length;
  idx = Math.max(0, Math.min(levels.length-1, idx + (direction >= 0 ? 1 : -1)));
  setBusGuideVisibility(true);
  setBusLevel(levels[idx], announce);
}
function finishBusDrag(clientX){
  if(!dragVehState.active || dragVehState.veh!=="bus") return;
  const bus=getDragBus("bus");
  const track=getDragTrack("bus");
  if(bus){
    bus.classList.remove("dragging");
    if(dragVehState.pointerId!=null && bus.releasePointerCapture){
      try{ bus.releasePointerCapture(dragVehState.pointerId); }catch(err){}
    }
  }
  if(track) track.classList.remove("drag-active");
  highlightBusPreview(null);
  dragVehState.active=false;
  dragVehState.veh=null;
  dragVehState.pointerId=null;
  const level=(typeof clientX==="number") ? getNearestBusLevel(clientX) : vehPick.bus;
  if(level) setBusLevel(level, false);
  else updateVehSelected();
}
function initBusDragSimulation(){
  const bus=getDragBus("bus");
  const track=getDragTrack("bus");
  if(!bus || !track) return;
  if(bus.dataset.dragReady==="1"){
    syncBusDragUI();
    return;
  }
  bus.dataset.dragReady="1";
  positionDragBus(vehPick.bus, true);

  bus.addEventListener("pointerdown", (e)=>{
    if(state.tasks.causas.veh){
      showToast((currentLang==="en") ? "Already done ✅" : "Ya está listo ✅");
      return;
    }
    setBusGuideVisibility(true);
    hideBusAutoHint();
    dragVehState.active=true;
    dragVehState.veh="bus";
    dragVehState.pointerId=e.pointerId;
    const rect=bus.getBoundingClientRect();
    dragVehState.offsetX=e.clientX-rect.left;
    bus.classList.add("dragging");
    track.classList.add("drag-active");
    if(bus.setPointerCapture){
      try{ bus.setPointerCapture(e.pointerId); }catch(err){}
    }
    e.preventDefault();
  });

  bus.addEventListener("keydown", (e)=>{
    if(state.tasks.causas.veh) return;
    const levels=["low","mid","high"];
    let idx=levels.indexOf(vehPick.bus || "mid");
    if(idx<0) idx=1;
    if(e.key==="ArrowRight" || e.key==="ArrowUp"){
      idx=Math.min(levels.length-1, idx+1);
      setBusGuideVisibility(true);
      setBusLevel(levels[idx], true);
      e.preventDefault();
    }
    if(e.key==="ArrowLeft" || e.key==="ArrowDown"){
      idx=Math.max(0, idx-1);
      setBusGuideVisibility(true);
      setBusLevel(levels[idx], true);
      e.preventDefault();
    }
    if(e.key===" " || e.key==="Enter"){
      if(!vehPick.bus){
        setBusGuideVisibility(true);
        setBusLevel("mid", true);
      }else{
        shiftBusLevel(1, true);
      }
      e.preventDefault();
    }
  });

  bus.addEventListener("click", (e)=>{
    if(e.defaultPrevented) return;
    if(state.tasks.causas.veh) return;
    setBusGuideVisibility(true);
    shiftBusLevel(1, true);
    e.preventDefault();
  });

  track.addEventListener("click", (e)=>{
    if(e.defaultPrevented) return;
    if(state.tasks.causas.veh) return;
    if(e.target && e.target.closest && e.target.closest('.drag-lane[data-veh="bus"], .drag-bus, .drag-arrow')) return;
    const level=getNearestBusLevel(typeof e.clientX==="number" ? e.clientX : (track.getBoundingClientRect().left + (track.clientWidth/2)));
    if(level){
      setBusGuideVisibility(true);
      setBusLevel(level, true);
    }
  });

  document.querySelectorAll('.drag-arrow[data-drag-step]').forEach((arrow)=>{
    if(arrow.dataset.busArrowReady==="1") return;
    arrow.dataset.busArrowReady="1";
    const dir=Number(arrow.getAttribute('data-drag-step') || '1');
    const move=(e)=>{
      if(e && e.defaultPrevented) return;
      if(state.tasks.causas.veh) return;
      setBusGuideVisibility(true);
      shiftBusLevel(dir, true);
      if(e){ e.preventDefault(); e.stopPropagation(); }
    };
    arrow.addEventListener('click', move);
    arrow.addEventListener('pointerup', move);
    arrow.addEventListener('keydown', (e)=>{
      if(e.key==='Enter' || e.key===' '){ move(e); }
    });
  });

  track.querySelectorAll('.drag-lane[data-veh="bus"]').forEach(lane=>{
    lane.addEventListener("click", (e)=>{
      if(e.defaultPrevented) return;
      if(state.tasks.causas.veh) return;
      setBusGuideVisibility(true);
      setBusLevel(lane.getAttribute("data-level"), true);
    });
  });

  document.addEventListener("pointermove", (e)=>{
    if(!dragVehState.active || dragVehState.veh!=="bus") return;
    const dragBus=getDragBus("bus");
    const dragTrack=getDragTrack("bus");
    if(!dragBus || !dragTrack) return;
    const rect=dragTrack.getBoundingClientRect();
    const min=8;
    const max=Math.max(min, dragTrack.clientWidth-dragBus.offsetWidth-8);
    let left=e.clientX-rect.left-dragVehState.offsetX;
    left=Math.max(min, Math.min(max, left));
    dragBus.classList.remove("no-anim");
    dragBus.style.left=`${left}px`;
    highlightBusPreview(getNearestBusLevel(e.clientX));
    e.preventDefault();
  });

  const endDrag=(e)=>{
    if(!dragVehState.active || dragVehState.veh!=="bus") return;
    finishBusDrag(typeof e.clientX==="number" ? e.clientX : null);
  };
  document.addEventListener("pointerup", endDrag);
  document.addEventListener("pointercancel", endDrag);
}
