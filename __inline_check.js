function anyCompleted(){ return Object.values(state.completed).some(Boolean); }
function saveState(){
  const payload=JSON.stringify({
    missionStarted:state.missionStarted,
    score:state.score,
    completed:state.completed,
    tasks:state.tasks,
    commitChoices:state.commitChoices,
    planData:state.planData,
    lastScreen:state.lastScreen,
    introClosed:state.introClosed
  });
  safeSet(localStorage,STORAGE_KEY,payload);
  safeSet(sessionStorage,SESSION_KEY,payload);
}
function loadState(){
  const raw=safeGet(sessionStorage,SESSION_KEY) || safeGet(localStorage,STORAGE_KEY);
  if(!raw) return;
  try{
    const d=JSON.parse(raw);
    state.missionStarted=!!d.missionStarted;
    state.score=Number(d.score||0);
    state.completed=Object.assign(state.completed,d.completed||{});
    state.tasks = Object.assign(state.tasks, d.tasks||{});
    state.tasks.causas = Object.assign({veh:false,quiz:false}, state.tasks.causas||{});
    state.tasks.consecuencias = Object.assign({seq:false,quiz:false}, state.tasks.consecuencias||{});
    state.tasks.soluciones = Object.assign({commit:false,quiz:false}, state.tasks.soluciones||{});
    state.commitChoices = Array.isArray(d.commitChoices)
      ? d.commitChoices.filter(v=> typeof v === "string")
      : [];
    state.planData = normalizePlanData(d.planData);
    if(state.completed.plan && (!isPlanDataReady() || !d.planData || Number(d.planData.version||0) < PLAN_FORM_VERSION)) state.completed.plan = false;
    state.lastScreen=(typeof d.lastScreen==="string"?d.lastScreen:"home");
    state.introClosed=!!d.introClosed;
    if(state.score>0 || anyCompleted()) state.missionStarted=true;
    if(!state.completed.plan && state.lastScreen==="cierre"){
      state.lastScreen = isPlanUnlocked() ? "plan" : (state.missionStarted ? "command" : "home");
    }
  }catch(e){}
}

