function shuffleArray(arr){
  for(let i=arr.length-1;i>0;i--){
    const j=Math.floor(Math.random()*(i+1));
    [arr[i],arr[j]]=[arr[j],arr[i]];
  }
  return arr;
}
function swapSeqCards(cardA, cardB){
  if(!cardA || !cardB || cardA===cardB || cardA.parentNode!==cardB.parentNode) return;
  const parent=cardA.parentNode;
  const marker=document.createElement("span");
  parent.replaceChild(marker, cardA);
  parent.replaceChild(cardA, cardB);
  parent.replaceChild(cardB, marker);
}
function clearSeqCardStates(kind){
  getSeqCards(kind).forEach(card=>card.classList.remove("selected","dragging","drop-target"));
}
function updateSeqProgress(kind, mode="auto") {
  const box=document.getElementById(`seq-${kind}-progress`);
  if(!box) return;
  if(seqState[kind].done || state.tasks.consecuencias.seq){
    box.innerHTML = (currentLang==="en")
      ? 'Status: <b>Correct order! 4/4</b>'
      : 'Estado: <b>¡Orden correcto! 4/4</b>';
    return;
  }
  if(mode==="selected"){
    box.innerHTML = (currentLang==="en")
      ? 'Status: <b>Card selected. Tap another to swap.</b>'
      : 'Estado: <b>Tarjeta seleccionada. Toca otra para intercambiar.</b>';
    return;
  }
  if(mode==="wrong"){
    box.innerHTML = (currentLang==="en")
      ? 'Status: <b>Not yet. Keep organizing and check again.</b>'
      : 'Estado: <b>Aún no. Sigue organizando y verifica de nuevo.</b>';
    return;
  }
  const order=getSeqOrder(kind);
  let inPlace=0;
  order.forEach((step,idx)=>{ if(step===SEQ_CORRECT[kind][idx]) inPlace++; });
  box.innerHTML = (currentLang==="en")
    ? `In place: <b>${inPlace}/4</b>`
    : `En su lugar: <b>${inPlace}/4</b>`;
}
function setSeqDone(kind){
  seqState[kind].done=true;
  seqState[kind].selected=null;
  clearSeqCardStates(kind);
  getSeqCards(kind).forEach(card=>{
    card.classList.add("done");
    card.disabled=true;
    card.draggable=false;
  });
}
function shuffleSeq(kind){
  if(state.tasks.consecuencias.seq) return;
  const container=getSeqContainer(kind);
  if(!container) return;
  const cards=getSeqCards(kind);
  let shuffled=cards.slice();
  let guard=0;
  do{
    shuffled=shuffleArray(shuffled.slice());
    guard++;
  }while(guard<12 && shuffled.map(card=>card.getAttribute("data-step")).join(",")===SEQ_CORRECT[kind].join(","));
  shuffled.forEach(card=>container.appendChild(card));
  seqState[kind].selected=null;
  seqState[kind].dragEl=null;
  getSeqCards(kind).forEach(card=>{
    card.classList.remove("done","selected","dragging","drop-target");
    card.disabled=false;
    card.draggable=true;
  });
  updateSeqProgress(kind);
}
function resetSeqUI(kind, silent=false){
  seqState[kind].done=false;
  shuffleSeq(kind);
  if(!silent) showToast((currentLang==="en") ? "Cards reshuffled!" : "¡Tarjetas mezcladas otra vez!");
}
function handleSeqTap(btn){
  const kind=btn.getAttribute("data-seq");
  if(state.tasks.consecuencias.seq || seqState[kind].done) return;
  if(seqState[kind].selected===btn){
    btn.classList.remove("selected");
    seqState[kind].selected=null;
    updateSeqProgress(kind);
    return;
  }
  if(!seqState[kind].selected){
    clearSeqCardStates(kind);
    btn.classList.add("selected");
    seqState[kind].selected=btn;
    updateSeqProgress(kind, "selected");
    return;
  }
  const first=seqState[kind].selected;
  seqState[kind].selected=null;
  first.classList.remove("selected");
  swapSeqCards(first, btn);
  updateSeqProgress(kind);
}
function checkSeqOrder(kind){
  if(state.tasks.consecuencias.seq || seqState[kind].done) return;
  const ok=getSeqOrder(kind).join(",")===SEQ_CORRECT[kind].join(",");
  if(ok){
    state.tasks.consecuencias.seq=true;
    setSeqDone(kind);
    addScore(5);
    showToast(t("t_correct"));
    saveState();
    refreshMissionLocks();
    updateSeqProgress(kind);
  }else{
    showToast(t("t_wrong"));
    updateSeqProgress(kind, "wrong");
    setTimeout(()=>updateSeqProgress(kind), 1200);
  }
}
function sortSeqToCorrect(kind){
  const container=getSeqContainer(kind);
  if(!container) return;
  const cards=getSeqCards(kind).sort((a,b)=>Number(a.getAttribute("data-step"))-Number(b.getAttribute("data-step")));
  cards.forEach(card=>container.appendChild(card));
}
function bindSeqDnD(kind){
  const container=getSeqContainer(kind);
  if(!container || container.dataset.seqBound==="1") return;
  container.dataset.seqBound="1";

  container.addEventListener("dragstart", (e)=>{
    const card=e.target.closest(`.seq-card[data-seq="${kind}"]`);
    if(!card || state.tasks.consecuencias.seq || seqState[kind].done) return;
    seqState[kind].dragEl=card;
    card.classList.add("dragging");
    try{ e.dataTransfer.setData("text/plain", card.getAttribute("data-step")); }catch(_e){}
    if(e.dataTransfer) e.dataTransfer.effectAllowed="move";
  });

  container.addEventListener("dragover", (e)=>{
    if(!seqState[kind].dragEl || state.tasks.consecuencias.seq || seqState[kind].done) return;
    e.preventDefault();
  });

  container.addEventListener("dragenter", (e)=>{
    const target=e.target.closest(`.seq-card[data-seq="${kind}"]`);
    if(!target || target===seqState[kind].dragEl) return;
    getSeqCards(kind).forEach(card=>card.classList.remove("drop-target"));
    target.classList.add("drop-target");
  });

  container.addEventListener("drop", (e)=>{
    if(!seqState[kind].dragEl || state.tasks.consecuencias.seq || seqState[kind].done) return;
    e.preventDefault();
    const target=e.target.closest(`.seq-card[data-seq="${kind}"]`);
    if(target && target!==seqState[kind].dragEl){
      swapSeqCards(seqState[kind].dragEl, target);
      updateSeqProgress(kind);
    }
    clearSeqCardStates(kind);
    seqState[kind].dragEl=null;
  });

  container.addEventListener("dragend", ()=>{
    clearSeqCardStates(kind);
    seqState[kind].dragEl=null;
  });
}

